void main() {
  int a = 5;
  print('Initial a: $a');

  print('Postfix increment (a++): ${a++}');
  print('Current a: $a');
  print('Prefix increment (++a): ${++a}');
  print('Current a: $a');

  print('Postfix decrement (a--): ${a--}');
  print('Current a: $a');
  print('Prefix decrement (--a): ${--a}');
  print('Current a: $a');
}
